-- Messaging (clc-app docs/MESSAGING.md): direct conversations between two
-- approved users, one helpdesk conversation per user, per-user read markers,
-- blocks, abuse reports, and the daily request quota.
--
-- People are referenced by users.id, which never leaves the server; the API
-- addresses them by checksummed wallet address. The conversation row is the
-- permission to message: two people need an accepted direct row first.
CREATE TABLE conversations (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    kind            TEXT NOT NULL,
    -- direct: user_a_id < user_b_id. helpdesk: user_a_id is the user, user_b_id is NULL.
    user_a_id       INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_b_id       INT REFERENCES users(id) ON DELETE CASCADE,
    status          TEXT NOT NULL,
    -- Who made the last status change: the requester, accepter, decliner, revoker or resolver.
    actor_id        INT REFERENCES users(id),
    intro           TEXT,
    last_message_at TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT conversations_shape CHECK (
        (kind = 'direct' AND user_b_id IS NOT NULL AND user_a_id < user_b_id
            AND status IN ('pending', 'accepted', 'declined', 'revoked'))
        OR
        (kind = 'helpdesk' AND user_b_id IS NULL
            AND status IN ('open', 'resolved'))
    ),
    CONSTRAINT conversations_intro_length CHECK (
        intro IS NULL OR CHAR_LENGTH(intro) <= 200
    )
);

CREATE UNIQUE INDEX conversations_direct_pair_unique
    ON conversations (user_a_id, user_b_id) WHERE kind = 'direct';
CREATE UNIQUE INDEX conversations_helpdesk_user_unique
    ON conversations (user_a_id) WHERE kind = 'helpdesk';
CREATE INDEX conversations_user_b_idx
    ON conversations (user_b_id) WHERE kind = 'direct';
CREATE INDEX conversations_helpdesk_queue_idx
    ON conversations (status, last_message_at DESC) WHERE kind = 'helpdesk';

CREATE TABLE messages (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_user_id  INT NOT NULL REFERENCES users(id),
    -- Generated by the client so a retried send is stored once.
    client_id       UUID NOT NULL,
    body            TEXT,
    image_urls      TEXT[] NOT NULL DEFAULT '{}',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT messages_has_content CHECK (
        NULLIF(BTRIM(body), '') IS NOT NULL OR CARDINALITY(image_urls) > 0
    ),
    CONSTRAINT messages_body_length CHECK (
        body IS NULL OR CHAR_LENGTH(body) <= 2000
    ),
    CONSTRAINT messages_image_count CHECK (CARDINALITY(image_urls) <= 4),
    CONSTRAINT messages_client_id_unique UNIQUE (sender_user_id, client_id)
);

CREATE INDEX messages_conversation_page_idx ON messages (conversation_id, id DESC);

CREATE TABLE conversation_reads (
    conversation_id      BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id              INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- A high-water mark, not a foreign key: pruning a message must not move it.
    last_read_message_id BIGINT NOT NULL,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE user_blocks (
    blocker_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT user_blocks_distinct CHECK (blocker_id <> blocked_id)
);

CREATE INDEX user_blocks_blocked_idx ON user_blocks (blocked_id);

-- Named abuse_reports so it does not clash with the existing reports (posts) table.
CREATE TABLE abuse_reports (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    reporter_id      INT NOT NULL REFERENCES users(id),
    reported_user_id INT NOT NULL REFERENCES users(id),
    message_id       BIGINT REFERENCES messages(id) ON DELETE SET NULL,
    comment          TEXT,
    status           TEXT NOT NULL DEFAULT 'open',
    resolved_by      INT REFERENCES users(id),
    resolved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT abuse_reports_status CHECK (status IN ('open', 'dismissed', 'actioned')),
    CONSTRAINT abuse_reports_comment_length CHECK (
        comment IS NULL OR CHAR_LENGTH(comment) <= 1000
    ),
    CONSTRAINT abuse_reports_distinct CHECK (reporter_id <> reported_user_id)
);

CREATE INDEX abuse_reports_queue_idx ON abuse_reports (status, created_at DESC);

-- One row per user per UTC day; the daily request quota.
CREATE TABLE messaging_request_quota (
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day     DATE NOT NULL,
    used    INT NOT NULL,
    PRIMARY KEY (user_id, day)
);

